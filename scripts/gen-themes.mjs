// Generate daisyUI multi-theme CSS that also re-maps django-unfold colors.
//
// Outputs:
//   - daisy-themes.css            (imported by styles.css, compiled into the bundle)
//   - whiteneuron/base/themes.py  (theme names/schemes for the admin theme picker)
//
// Usage: node scripts/gen-themes.mjs   (run automatically by scripts/tailwind.sh)
//        WN_THEMES="light,dark,dracula" node scripts/gen-themes.mjs   (subset, smaller CSS)

import { writeFileSync } from "node:fs";
import themes from "daisyui/theme/object.js";

// light/dark follow the project's UNFOLD["COLORS"]: daisyUI's base and primary point at
// unfold's palette (resolved at runtime), so daisyUI components (buttons, selects,
// alerts...) sit on the same surfaces as unfold's own widgets. daisyUI's stock dark
// base (a gray slate) looked like gray blocks on unfold's navy dark background.
const OVERRIDES = {
  light: {
    "--color-base-100": "oklch(100% 0 0)",
    "--color-base-200": "var(--color-base-50)",
    "--color-base-300": "var(--color-base-100)",
    "--color-base-content": "var(--color-base-900)",
    "--color-primary": "var(--color-primary-600)",
    "--color-primary-content": "oklch(100% 0 0)",
  },
  dark: {
    // unfold dark: page/cards on base-900, darker wells on base-950, text base-100
    "--color-base-100": "var(--color-base-900)",
    "--color-base-200": "color-mix(in oklab, var(--color-base-900), var(--color-base-950))",
    "--color-base-300": "var(--color-base-950)",
    "--color-base-content": "var(--color-base-100)",
    "--color-primary": "var(--color-primary-500)",
    "--color-primary-content": "oklch(100% 0 0)",
  },
};

// light/dark keep the palette configured in UNFOLD["COLORS"]; every other theme
// derives unfold's primary/base scales from its own daisyUI colors.
const KEEP_UNFOLD_COLORS = new Set(["light", "dark"]);

// daisyUI base-100/200/300 collide with unfold's gray scale (--color-base-*),
// so they are exposed as --ui-color-base-* and re-scoped onto daisyUI
// components in styles.css.
const COLLIDING = new Set(["--color-base-100", "--color-base-200", "--color-base-300"]);

// Colors are mixed at build time (linear interpolation in OKLab, same as CSS
// `color-mix(in oklab, ...)`) so the bundle ships plain oklch() values.
const parse = (v) => {
  const m = /^oklch\(([\d.]+)%\s+([\d.]+)\s+([\d.]+)\)$/.exec(v.trim());
  if (!m) throw new Error(`Unsupported color: ${v}`);
  const [L, C, h] = [m[1] / 100, +m[2], (m[3] * Math.PI) / 180];
  return [L, C * Math.cos(h), C * Math.sin(h)];
};
const format = ([L, a, b]) => {
  const C = Math.hypot(a, b);
  const h = C < 1e-4 ? 0 : ((Math.atan2(b, a) * 180) / Math.PI + 360) % 360;
  const r = (n, d) => +n.toFixed(d);
  return `oklch(${r(L * 100, 2)}% ${r(C, 4)} ${r(h, 2)})`;
};
const WHITE = "oklch(100% 0 0)";
const BLACK = "oklch(0% 0 0)";
// pct% of `color` mixed with (100 - pct)% of `other`
const mix = (color, pct, other) => {
  const [x, y, t] = [parse(color), parse(other), pct / 100];
  return format(x.map((c, i) => c * t + y[i] * (1 - t)));
};

// Weight -> [percentage of primary, mixed with]. 500 is the theme primary itself.
const PRIMARY_STEPS = {
  50: [8, WHITE], 100: [16, WHITE], 200: [32, WHITE], 300: [52, WHITE], 400: [76, WHITE],
  500: [100, WHITE],
  600: [88, BLACK], 700: [75, BLACK], 800: [62, BLACK], 900: [50, BLACK], 950: [36, BLACK],
};

// unfold's base scale always runs light (50) -> dark (950). Light themes use it
// as "background -> text", dark themes as "text -> background".
// Weight -> percentage of base-content mixed into base-100 (or a daisy base color).
const BASE_STEPS_LIGHT = {
  50: "--color-base-200", 100: "--color-base-300",
  200: 14, 300: 24, 400: 40, 500: 54, 600: 66, 700: 76, 800: 85, 900: 92, 950: 96,
};
const BASE_STEPS_DARK = {
  50: 96, 100: 92, 200: 85, 300: 75, 400: 60, 500: 45, 600: 30, 700: 16, 800: 8,
  900: "--color-base-100", 950: "--color-base-300",
};
const FONT = {
  "subtle-light": "var(--color-base-500)",
  "default-light": "var(--color-base-600)",
  "important-light": "var(--color-base-900)",
  "subtle-dark": "var(--color-base-400)",
  "default-dark": "var(--color-base-300)",
  "important-dark": "var(--color-base-100)",
};

const decl = (vars) =>
  Object.entries(vars)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join("\n");

const wanted = (process.env.WN_THEMES || "").split(",").map((n) => n.trim()).filter(Boolean);
const names = Object.keys(themes).filter((n) => !wanted.length || wanted.includes(n) || n === "light" || n === "dark").sort((a, b) => {
  // light & dark first, then alphabetical
  const rank = (n) => (n === "light" ? 0 : n === "dark" ? 1 : 2);
  return rank(a) - rank(b) || a.localeCompare(b);
});

let css = `/* AUTO-GENERATED by scripts/gen-themes.mjs — do not edit by hand. */\n`;
const schemes = {};

for (const name of names) {
  const theme = { ...themes[name], ...(OVERRIDES[name] || {}) };
  const scheme = theme["color-scheme"] === "dark" ? "dark" : "light";
  schemes[name] = scheme;

  // 1) daisyUI tokens. Works on <html> and on nested previews (theme picker swatches).
  const daisyVars = {};
  for (const [k, v] of Object.entries(theme)) {
    if (k === "color-scheme") continue;
    daisyVars[COLLIDING.has(k) ? k.replace("--color-", "--ui-color-") : k] = v;
  }
  const sel = name === "light"
    ? `:root:not([data-theme]), [data-theme="light"]`
    : `[data-theme="${name}"]`;
  css += `\n${sel} {\n  color-scheme: ${scheme};\n${decl(daisyVars)}\n}\n`;

  // 2) unfold tokens. html[...] (0,1,1) beats unfold's inline ":root" (0,1,0).
  if (!KEEP_UNFOLD_COLORS.has(name)) {
    const unfoldVars = {};
    for (const [w, [pct, other]] of Object.entries(PRIMARY_STEPS)) {
      unfoldVars[`--color-primary-${w}`] = mix(theme["--color-primary"], pct, other);
    }
    const steps = scheme === "dark" ? BASE_STEPS_DARK : BASE_STEPS_LIGHT;
    for (const [w, step] of Object.entries(steps)) {
      unfoldVars[`--color-base-${w}`] = typeof step === "string"
        ? theme[step]
        : mix(theme["--color-base-content"], step, theme["--color-base-100"]);
    }
    for (const [k, v] of Object.entries(FONT)) unfoldVars[`--color-font-${k}`] = v;
    css += `html[data-theme="${name}"] {\n${decl(unfoldVars)}\n}\n`;
  }
}

writeFileSync("daisy-themes.css", css);

const py = `# AUTO-GENERATED by scripts/gen-themes.mjs — do not edit by hand.
# daisyUI themes compiled into base/css/styles.css, mapped to their color scheme.
DAISYUI_THEMES = {
${names.map((n) => `    "${n}": "${schemes[n]}",`).join("\n")}
}
`;
writeFileSync("whiteneuron/base/themes.py", py);

console.log(`Generated ${names.length} themes.`);
